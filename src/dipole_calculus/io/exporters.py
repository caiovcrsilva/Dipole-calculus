"""Exporters for Gaussian CUBE volumetric files and VMD TCL visualization scripts."""

import numpy as np

# Conversion factor from Angstrom to Bohr
ANGSTROM_TO_BOHR = 1.8897259886


def export_cube(filename, grid_data, min_coords, max_coords, resolution, box_edges):
    """Export 3D volumetric grid data to a Gaussian .cube file."""
    nx, ny, nz = resolution

    # Compute grid spacing along each axis
    step_x = (max_coords[0] - min_coords[0]) / (nx - 1)
    step_y = (max_coords[1] - min_coords[1]) / (ny - 1)
    step_z = (max_coords[2] - min_coords[2]) / (nz - 1)

    # Convert grid origin to Bohr units
    orig_x = min_coords[0] * ANGSTROM_TO_BOHR
    orig_y = min_coords[1] * ANGSTROM_TO_BOHR
    orig_z = min_coords[2] * ANGSTROM_TO_BOHR

    center_x = orig_x + ((box_edges[0] / 2.0) * ANGSTROM_TO_BOHR)
    center_y = orig_y + ((box_edges[1] / 2.0) * ANGSTROM_TO_BOHR)
    center_z = orig_z + ((box_edges[2] / 2.0) * ANGSTROM_TO_BOHR)

    with open(filename, "w") as f:
        f.write("Mean curl\n")
        f.write("Generated by dipole_calculus\n")
        # Dummy atom count and grid origin coordinates in Bohr
        f.write(f"    1 {orig_x:12.6f} {orig_y:12.6f} {orig_z:12.6f}\n")
        # Number of grid points and step vectors in Bohr for each axis
        f.write(f"{nx:5d} {step_x * ANGSTROM_TO_BOHR:12.6f}     0.000000     0.000000\n")
        f.write(f"{ny:5d}     0.000000 {step_y * ANGSTROM_TO_BOHR:12.6f}     0.000000\n")
        f.write(f"{nz:5d}     0.000000     0.000000 {step_z * ANGSTROM_TO_BOHR:12.6f}\n")
        f.write(f"    1     0.000000 {center_x:12.6f} {center_y:12.6f} {center_z:12.6f}\n")

        # Write 3D volumetric values (6 values per line along the Z axis)
        for ix in range(nx):
            for iy in range(ny):
                for iz in range(nz):
                    f.write(f"{grid_data[ix, iy, iz]:13.5E}")
                    if (iz + 1) % 6 == 0:
                        f.write("\n")
                if nz % 6 != 0:
                    f.write("\n")


def export_tcl_script(cube_filename, grid_data, tcl_filename="plot_cube.vmd"):
    """Generate a VMD TCL script to visualize the .cube file with percentile-clipped color scaling."""
    # Filter extreme outliers by using the 2nd and 98th percentiles
    min_val = np.percentile(grid_data, 2)
    max_val = np.percentile(grid_data, 98)

    # Set initial isovalue to global mean plus half standard deviation
    mean_val = np.mean(grid_data)
    std_val = np.std(grid_data)
    iso_val = mean_val + (std_val * 0.5)

    with open(tcl_filename, "w") as f:
        f.write("# Script automatically generated by dipole_calculus\n")
        f.write(f"set min_val {min_val:.5E}\n")
        f.write(f"set max_val {max_val:.5E}\n")
        f.write(f"set iso_val {iso_val:.5E}\n\n")

        f.write("display projection orthographic\n")
        f.write("color scale method BWR\n\n")

        f.write(f"mol new {cube_filename} type cube waitfor all\n\n")

        f.write("mol delrep 0 top\n")
        f.write("mol addrep top\n")
        f.write("mol modcolor 0 top Volume 0\n")
        f.write("mol scaleminmax top 0 $min_val $max_val\n")
        f.write("mol modstyle 0 top Isosurface $iso_val 0 2 0 1 1\n")
        f.write("mol modmaterial 0 0 Glass2\n\n")
